/* Real settings UI: explicit transports, scoped registration and Windows/WSL output. */
'use strict';
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { mkdtempSync, rmSync, readFileSync } = require('node:fs');
const { join, resolve } = require('node:path');
const { tmpdir } = require('node:os');
const { once } = require('node:events');
const { chromium } = require('playwright');
const directory = mkdtempSync(join(tmpdir(), 'joongi-connections-browser-'));
const child = spawn(process.env.PYTHON || 'python3', ['-B', '-m', 'tests.fixtures.managed_hub', directory], { cwd: resolve(__dirname, '..'), stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
async function main() {
  const fixture = await new Promise((accept, reject) => { const timer = setTimeout(() => reject(Error('Startup timeout')), 15000); child.stdout.once('data', data => { clearTimeout(timer); accept(JSON.parse(String(data))); }); child.once('error', reject); });
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.ui_url);
  await page.getByRole('heading', { name: '나의 도구를 연결하는 곳' }).waitFor();
  await page.getByText('임시 저장소를 사용 중입니다.', { exact: false }).waitFor();
  await page.getByRole('button', { name: '연결 설정', exact: true }).click();
  const mode = page.getByLabel('Hub 연결 방식');
  await mode.waitFor(); assert.equal(await mode.inputValue(), 'stdio');
  assert(!await page.getByLabel('HTTP Hub 주소').isVisible());
  await mode.selectOption('hybrid');
  await page.getByLabel('HTTP Hub가 꺼져 있을 때').selectOption('error');
  await page.getByRole('button', { name: '연결 방식 저장', exact: true }).click();
  await page.getByText('연결 방식을 저장했습니다.', { exact: false }).waitFor();
  await page.waitForFunction(() => document.querySelector('#connection-mode')?.value === 'hybrid' && !document.querySelector('[data-preserve="connection-settings"]').dataset.dirty);
  assert.equal(await page.getByLabel('HTTP Hub가 꺼져 있을 때').inputValue(), 'error');
  await page.getByRole('heading', { name: '내 에이전트에 등록', exact: true }).waitFor();
  await page.locator('[data-preserve="connection-settings"]').getByLabel('codex', { exact: true }).check();
  await page.getByRole('button', { name: '에이전트 등록 계획 보기', exact: true }).click();
  await page.getByRole('button', { name: '에이전트 등록 적용', exact: true }).click();
  await page.getByText('에이전트에 연결을 등록했습니다.', { exact: false }).waitFor();
  assert(readFileSync(join(directory, 'home/.codex/config.toml'), 'utf8').includes('"hybrid"'));
  await mode.selectOption('http');
  await page.getByRole('button', { name: '연결 방식 저장', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#connection-mode')?.value === 'http' && !document.querySelector('[data-preserve="connection-settings"]').dataset.dirty);
  await page.locator('[data-preserve="connection-settings"]').getByLabel('codex', { exact: true }).check();
  await page.getByRole('button', { name: '에이전트 등록 계획 보기', exact: true }).click();
  await page.getByRole('button', { name: '에이전트 등록 적용', exact: true }).click();
  await page.getByText('에이전트에 연결을 등록했습니다.', { exact: false }).waitFor();
  assert(readFileSync(join(directory, 'home/.codex/config.toml'), 'utf8').includes('"http"'));
  await page.getByText('수동 연결 설정', { exact: true }).click();
  await page.getByLabel('설정을 볼 에이전트').selectOption('gemini');
  await page.locator('pre').filter({ hasText: 'command' }).waitFor();
  await page.screenshot({ path: join(directory, 'settings-desktop.png'), fullPage: true });
  // Register a project, then override the inherited HTTP setting with pure stdio.
  await page.evaluate(async root => { await api('/api/v1/projects', { method: 'POST', body: JSON.stringify({ id: 'connection-project', root, common_skills: ['usual-korean'], common_servers: [] }) }); await loadProjects(); }, fixture.project);
  await page.getByLabel('작업 범위').selectOption('connection-project');
  await page.waitForFunction(() => document.querySelector('#page').dataset.profile === 'connection-project');
  await page.getByLabel('공용 기본 설정 따르기', { exact: true }).uncheck();
  await mode.selectOption('stdio');
  await page.getByRole('button', { name: '연결 방식 저장', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#connection-mode')?.value === 'stdio' && !document.querySelector('[data-preserve="connection-settings"]').dataset.dirty);
  await page.locator('[data-preserve="connection-settings"]').getByLabel('claude', { exact: true }).check();
  await page.getByRole('button', { name: '에이전트 등록 계획 보기', exact: true }).click();
  await page.getByRole('button', { name: '에이전트 등록 적용', exact: true }).click();
  await page.getByText('에이전트에 연결을 등록했습니다.', { exact: false }).waitFor();
  const projectConfig = JSON.parse(readFileSync(join(fixture.project, '.mcp.json'), 'utf8'));
  assert(projectConfig.mcpServers['joongi-hub'].args.includes('connection-project'));
  assert(projectConfig.mcpServers['joongi-hub'].args.includes('stdio'));
  await page.getByText('수동 연결 설정', { exact: true }).click();
  await page.getByText('Windows 에이전트에서 WSL 사용', { exact: true }).click();
  await page.getByLabel('WSL 배포판 이름').fill('Ubuntu');
  await page.getByRole('button', { name: 'Windows용 WSL 연결 생성', exact: true }).click();
  await page.locator('pre').filter({ hasText: 'wsl.exe' }).waitFor();
  await page.setViewportSize({ width: 390, height: 900 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: join(directory, 'settings-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Connection settings browser passed: stdio/hybrid/HTTP, fallback, global/project agent registration, native config, WSL output, mobile');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); if (child.exitCode === null) { const done = once(child, 'exit'); child.kill('SIGINT'); await done; } if (process.env.KEEP_CONNECTION_FIXTURE) console.log(`Connection screenshots: ${directory}`); else rmSync(directory, { recursive: true, force: true }); });
