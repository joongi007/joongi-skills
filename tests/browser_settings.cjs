const read = () => lines.length ? Promise.resolve(lines.shift()) : new Promise((resolve, reject) => { const timer = setTimeout(() => reject(Error('Fixture timeout')), 15000); readers.push(row => { clearTimeout(timer); resolve(row); }); });
